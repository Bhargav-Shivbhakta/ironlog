// Interpolates the tithi (1-15 within its paksha) for any date between
// two verified anchors. Returns null outside the 2026-2027 range.
function getTithiInfo(dateStr){
  let before = null, after = null;
  for(let i=0;i<ALL_ANCHORS.length-1;i++){
    if(ALL_ANCHORS[i].date<=dateStr && ALL_ANCHORS[i+1].date>=dateStr){ before = ALL_ANCHORS[i]; after = ALL_ANCHORS[i+1]; break; }
  }
  if(!before || !after) return null;
  if(dateStr===before.date) return { paksha: before.tithi===0?'Krishna':'Shukla', tithiNum: 15, name: before.tithi===0?'Amavasya':'Purnima', isAnchor:true, anchorName: before.name };
  const span = daysBetween(before.date, after.date) || 1;
  const pos = daysBetween(before.date, dateStr);
  const frac = pos/span; // 0..1 across the half-lunar-month
  const tithiNum = Math.min(15, Math.max(1, Math.round(frac*15)+ (before.tithi===0?0:0) ));
  const paksha = before.tithi===0 ? 'Shukla' : 'Krishna'; // after Amavasya = waxing(Shukla); after Purnima = waning(Krishna)
  const names = paksha==='Shukla' ? TITHI_NAMES_SHUKLA : TITHI_NAMES_KRISHNA;
  const isAnchorDay = tithiNum===15 && dateStr===after.date;
  return { paksha: paksha, tithiNum: tithiNum, name: names[tithiNum-1], isAnchor:isAnchorDay, anchorName: isAnchorDay?after.name:null };
}

